export function resolveKlyxAccountsPageLocale(
  locale: string
): KlyxAccountsPageLocale {
  return KLYX_ACCOUNTS_PAGE_TRANSLATED_LOCALES.includes(
    locale as KlyxAccountsPageLocale
  )
    ? (locale as KlyxAccountsPageLocale)
    : "fr";
}

export function translateKlyxAccountsPage(
  locale: string,
  key: KlyxAccountsPageMessageKey,
  values: KlyxAccountsPageMessageValues = {}
): string {
  const template = dictionaries[resolveKlyxAccountsPageLocale(locale)][key];

  return Object.entries(values).reduce(
    (message, [name, value]) =>
      message.replaceAll(`{{${name}}}`, String(value)),
    template
  );
}

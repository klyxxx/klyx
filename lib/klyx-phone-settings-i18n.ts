export function resolveKlyxPhoneSettingsLocale(locale: string): KlyxPhoneSettingsLocale {
  return (KLYX_PHONE_SETTINGS_TRANSLATED_LOCALES as readonly string[]).includes(locale)
    ? (locale as KlyxPhoneSettingsLocale)
    : "fr";
}

export function translateKlyxPhoneSettings(
  locale: string,
  key: KlyxPhoneSettingsMessageKey,
  variables: Readonly<Record<string, string | number>> = {}
): string {
  const resolved = resolveKlyxPhoneSettingsLocale(locale);
  return Object.entries(variables).reduce(
    (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
    dictionaries[resolved][key]
  );
}

export function resolveKlyxPhoneSettingsPublicErrorKey(
  message: string | undefined,
  fallback: KlyxPhoneSettingsMessageKey
): KlyxPhoneSettingsMessageKey {
  return (message && publicErrors[message]) || fallback;
}

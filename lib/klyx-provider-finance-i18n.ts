const DICTIONARIES: Record<KlyxProviderFinanceLocale, Dictionary> = {
  fr: FR,
  en: EN,
  nl: NL,
  de: DE,
};

export function resolveKlyxProviderFinanceLocale(
  locale: string
): KlyxProviderFinanceLocale {
  return KLYX_PROVIDER_FINANCE_TRANSLATED_LOCALES.includes(
    locale as KlyxProviderFinanceLocale
  )
    ? (locale as KlyxProviderFinanceLocale)
    : "fr";
}

export function translateKlyxProviderFinance(
  locale: string,
  key: KlyxProviderFinanceMessageKey,
  values: KlyxProviderFinanceMessageValues = {}
): string {
  const template =
    DICTIONARIES[resolveKlyxProviderFinanceLocale(locale)][key];

  return Object.entries(values).reduce(
    (message, [name, value]) =>
      message.replaceAll(`{{${name}}}`, String(value)),
    template
  );
}

export function klyxProviderFinanceIntlLocale(locale: string): string {
  return getKlyxLocaleMetadata(normalizeKlyxLocale(locale)).htmlLang;
}

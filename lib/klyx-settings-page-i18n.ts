export function resolveKlyxSettingsPageLocale(
  locale: string
): KlyxSettingsPageLocale {
  return KLYX_SETTINGS_PAGE_TRANSLATED_LOCALES.includes(
    locale as KlyxSettingsPageLocale
  )
    ? (locale as KlyxSettingsPageLocale)
    : "fr";
}

export function translateKlyxSettingsPage(
  locale: string,
  key: KlyxSettingsPageMessageKey
): string {
  return dictionaries[resolveKlyxSettingsPageLocale(locale)][key];
}

export function resolveKlyxSettingsDeleteErrorKey(
  error: unknown
): KlyxSettingsPageMessageKey {
  if (typeof error !== "string") return "deleteFailed";
  return accountDeletePublicErrors[error] ?? "deleteFailed";
}

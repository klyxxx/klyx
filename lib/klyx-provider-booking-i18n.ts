export function resolveKlyxProviderBookingLocale(
  locale: string
): KlyxProviderBookingLocale {
  return KLYX_PROVIDER_BOOKING_TRANSLATED_LOCALES.includes(
    locale as KlyxProviderBookingLocale
  )
    ? (locale as KlyxProviderBookingLocale)
    : "fr";
}

export function translateKlyxProviderBooking(
  locale: string,
  key: KlyxProviderBookingMessageKey,
  values: KlyxProviderBookingMessageValues = {}
): string {
  const template = dictionaries[resolveKlyxProviderBookingLocale(locale)][key];

  return Object.entries(values).reduce(
    (message, [name, value]) =>
      message.replaceAll(`{{${name}}}`, String(value)),
    template
  );
}
